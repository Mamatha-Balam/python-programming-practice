# max() and min()
numbers = [10, 5, 8, 15, 3]

print("Max:", max(numbers))
print("Min:", min(numbers))


# sum()
numbers = [1, 2, 3, 4, 5]

print("Sum:", sum(numbers))


# range()
my_range = range(5)
print(list(my_range))


# sorted()
numbers = [3, 1, 4, 1, 5, 9, 2, 6]

sorted_numbers = sorted(numbers)
print("Sorted:", sorted_numbers)


# Additional example
data = [7, 2, 9, 4]

print("Max:", max(data))
print("Min:", min(data))
print("Sum:", sum(data))
print("Sorted Desc:", sorted(data, reverse=True))